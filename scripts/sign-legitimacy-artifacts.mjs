// Sign the AXIS Prime registry-legitimacy artifacts (v0.3 candidate C §1):
//   - the registry self-manifest (/.well-known/axis-registry), signed by the
//     Kipple registry-signing key;
//   - the root directory (/.well-known/axis-directory), signed by the AXIS
//     Prime ROOT key.
// Run when registrars change (rare). Keys are passed as JWK file paths — pull
// them from 1Password (op read / op item get) to a temp file, run, then delete.
//
// Usage:
//   node scripts/sign-legitimacy-artifacts.mjs <root.jwk.json> <registry.jwk.json>
//
// Outputs signed JSON to src/legitimacy/{root-directory.json,registry-manifest.json}
// (public, safe to commit) and prints the root PUBLIC key to pin in the worker.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { jcsCanonicalize } from '../src/utils/jcs.js';

const { subtle } = globalThis.crypto;
const TE = new TextEncoder();
const b64u = (b) => Buffer.from(b).toString('base64').replace(/\+/g, '-').replace(/\//g, '_').replace(/=+$/, '');
const HERE = path.dirname(fileURLToPath(import.meta.url));
const OUT = path.join(HERE, '..', 'src', 'legitimacy');

const [, , rootPath, regPath] = process.argv;
if (!rootPath || !regPath) { console.error('usage: node scripts/sign-legitimacy-artifacts.mjs <root.jwk.json> <registry.jwk.json>'); process.exit(1); }

// Timestamps. "For now" we issue a long-lived directory (1 year) since there is
// no auto-refresh yet; tighten to a ~7-day window with scheduled re-signing
// when this moves off the manual path.
const NOW = new Date();
const iso = (d) => d.toISOString().replace(/\.\d{3}Z$/, 'Z');
const issuedAt = iso(NOW);
const expiresAt = iso(new Date(NOW.getTime() + 365 * 86400_000));

const REGISTRY_URL = 'https://registry.axisprime.ai';

async function load(p) {
  const jwk = JSON.parse(fs.readFileSync(p, 'utf8'));
  const key = await subtle.importKey('jwk', jwk, { name: 'Ed25519' }, false, ['sign']);
  const pubB64 = jwk.x; // OKP `x` IS the base64url raw public key
  const fp = Buffer.from(await subtle.digest('SHA-256', Buffer.from(pubB64.replace(/-/g, '+').replace(/_/g, '/'), 'base64'))).toString('hex');
  return { key, pubB64, fp };
}
async function sign(key, obj) {
  return b64u(new Uint8Array(await subtle.sign('Ed25519', key, TE.encode(jcsCanonicalize(obj)))));
}

const root = await load(rootPath);
const reg = await load(regPath);

// 1) Registry self-manifest, signed by the registry-signing key.
const manifestBody = {
  axis_version: '0.3',
  registry_id: 'prime',
  registry_url: REGISTRY_URL,
  keys: [{ kid: 'prime-registry-2026', alg: 'Ed25519', public_key: reg.pubB64, status: 'active', not_before: issuedAt, not_after: expiresAt }],
  endpoints: { agents: '/agents', operators: '/operators', verify: '/verify', revocation: '/revocation', delegations: '/delegations' },
  directory_url: `${REGISTRY_URL}/.well-known/axis-directory`,
};
const manifest = { ...manifestBody, signature: await sign(reg.key, manifestBody) };

// 2) Root directory, signed by the Prime root key. Certifies registry "prime"
//    with the registry-signing key's fingerprint.
const directoryBody = {
  axis_version: '0.3',
  directory_version: 1,
  issued_at: issuedAt,
  expires_at: expiresAt,
  registrars: [{ registry_id: 'prime', registry_url: REGISTRY_URL, key_fingerprints: [reg.fp], status: 'certified', certified_at: issuedAt }],
};
const directory = { ...directoryBody, root_signature: await sign(root.key, directoryBody) };

fs.mkdirSync(OUT, { recursive: true });
fs.writeFileSync(path.join(OUT, 'registry-manifest.json'), JSON.stringify(manifest, null, 2));
fs.writeFileSync(path.join(OUT, 'root-directory.json'), JSON.stringify(directory, null, 2));

// Worker-importable ES module (inlined objects — no JSON import attributes, so
// no wrangler bundling surprises). This is what src/index.js serves.
const moduleSrc =
  `// GENERATED by scripts/sign-legitimacy-artifacts.mjs — do not edit by hand.\n` +
  `// Signed registry-legitimacy artifacts (v0.3 candidate C §1). Public.\n` +
  `export const REGISTRY_MANIFEST = ${JSON.stringify(manifest, null, 2)};\n\n` +
  `export const ROOT_DIRECTORY = ${JSON.stringify(directory, null, 2)};\n\n` +
  `// AXIS Prime root PUBLIC key (pin); verifiers check ROOT_DIRECTORY against it.\n` +
  `export const PRIME_ROOT_PUBLIC_KEY = ${JSON.stringify(root.pubB64)};\n`;
fs.writeFileSync(path.join(OUT, 'artifacts.js'), moduleSrc);

console.log('Wrote src/legitimacy/{registry-manifest.json, root-directory.json, artifacts.js}');
console.log('PIN THIS in the worker (AXIS Prime root PUBLIC key):', root.pubB64);
console.log('directory certifies registry "prime" with fingerprint:', reg.fp);
